import { useState } from "react";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { formatCurrency } from "@/utils/formatters";
import { DashboardData } from "@/hooks/useDashboardData";
import { Download, FileText, FileSpreadsheet, Printer, Sparkles, Check } from "lucide-react";
import { toast } from "sonner";

interface DashboardExecutiveSummaryProps {
  data: DashboardData;
  timeRange: string;
  selectedLocation: string;
  userDisplayName: string;
}

export function DashboardExecutiveSummary({
  data,
  timeRange,
  selectedLocation,
  userDisplayName,
}: DashboardExecutiveSummaryProps) {
  const [isExporting, setIsExporting] = useState(false);

  // Generate CSV summary
  const exportCSV = () => {
    try {
      setIsExporting(true);
      const rows = [
        ["PUIDO SMART SOLUTIONS - EXECUTIVE STORE PERFORMANCE REPORT"],
        [`Generated On`, new Date().toLocaleString()],
        [`Generated By`, userDisplayName],
        [`Reporting Period`, timeRange.toUpperCase()],
        [`Location Filter`, selectedLocation === "all" ? "All Locations" : selectedLocation],
        [],
        ["EXECUTIVE KPI METRICS"],
        ["Total Revenue", data.metrics.totalRevenue],
        ["Cost of Goods Sold (COGS)", data.metrics.cogs],
        ["Gross Profit", data.metrics.grossProfit],
        ["Total Expenses", data.metrics.totalExpenses],
        ["Net Profit", data.metrics.netProfit],
        ["Gross Margin %", `${data.metrics.grossMargin}%`],
        ["Net Margin %", `${data.metrics.netMargin}%`],
        [],
        ["INVENTORY ASSETS & HEALTH"],
        ["Total Stock Units", data.inventoryHealth.totalStockUnits],
        ["Total Active SKUs", data.inventoryHealth.totalSkus],
        ["Total Inventory Valuation", data.inventoryHealth.inventoryValuation],
        ["Out of Stock SKUs", data.inventoryHealth.outOfStockCount],
        ["Low Stock Items Count", data.inventoryHealth.lowStockItems.length],
        [],
        ["LOW STOCK RISK ITEMS"],
        ["Item ID", "Item Description", "Location", "Quantity Available", "Cost Price", "Selling Price"],
        ...data.inventoryHealth.lowStockItems.map((item) => [
          item.id,
          `"${item.description.replace(/"/g, '""')}"`,
          item.location || "Main",
          item.quantity,
          item.costPrice,
          item.actualPrice,
        ]),
        [],
        ["RECENT SALES OVERVIEW"],
        ["Invoice/Sale ID", "Item Description", "Quantity", "Amount", "Payment Status", "Sale Date"],
        ...data.recentSales.map((s) => [
          s.id,
          `"${s.itemDescription.replace(/"/g, '""')}"`,
          s.quantity,
          s.totalAmount,
          s.paymentStatus,
          s.saleDate,
        ]),
      ];

      const csvContent = "data:text/csv;charset=utf-8," + rows.map((e) => e.join(",")).join("\n");
      const encodedUri = encodeURI(csvContent);
      const link = document.createElement("a");
      link.setAttribute("href", encodedUri);
      link.setAttribute(
        "download",
        `Executive_Report_${timeRange}_${new Date().toISOString().split("T")[0]}.csv`
      );
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);

      toast.success("Executive CSV Report downloaded successfully");
    } catch (err) {
      console.error("Export error:", err);
      toast.error("Failed to generate CSV export");
    } finally {
      setIsExporting(false);
    }
  };

  // Printable Executive PDF Summary
  const printReport = () => {
    window.print();
  };

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button
          variant="outline"
          size="sm"
          disabled={isExporting}
          className="h-9 text-xs gap-1.5 border-border/80 bg-background/80 hover:bg-muted/80 shadow-2xs"
        >
          <Download className="h-3.5 w-3.5 text-primary" />
          <span className="hidden sm:inline">Export Report</span>
          <span className="sm:hidden">Export</span>
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-56 p-1.5 shadow-lg border-border">
        <DropdownMenuLabel className="text-xs font-semibold text-muted-foreground flex items-center gap-1.5">
          <Sparkles className="h-3.5 w-3.5 text-primary" />
          <span>Executive Store Summary</span>
        </DropdownMenuLabel>
        <DropdownMenuSeparator />
        <DropdownMenuItem onClick={exportCSV} className="text-xs cursor-pointer">
          <FileSpreadsheet className="h-4 w-4 mr-2 text-emerald-600" />
          <span>Export Excel / CSV Report</span>
        </DropdownMenuItem>
        <DropdownMenuItem onClick={printReport} className="text-xs cursor-pointer">
          <Printer className="h-4 w-4 mr-2 text-blue-600" />
          <span>Print / Save as PDF Snapshot</span>
        </DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
